_VALUES: dict[str, int] = {
    **{form: value for value, forms in _CARDINALS.items() for form in forms.split()},
    **{stem + end: value for value, stem in _SOFT_STEMS.items() for end in ("ь", "и", "ью")},
}
_WORD = re.compile(r"[а-яё]+", re.IGNORECASE)
_THOUSAND = 1000
_TEENS = range(10, 20)


def word_numbers(text: str) -> list[int]:
    """Числа, названные словами, в порядке текста; слова подряд складываются в одно число."""
    numbers: list[int] = []
    run: list[int] = []
    end = 0
    for match in _WORD.finditer(text):
        value = _VALUES.get(match.group().lower().replace("ё", "е"))
        if run and (value is None or text[end : match.start()].strip()):
            numbers.extend(_compose(run))
            run = []
        if value is not None:
            run.append(value)
            end = match.end()
    return numbers + _compose(run)


def _compose(run: list[int]) -> list[int]:
    """«девятьсот семьдесят два» — одно число; «два три» — два: разряды должны убывать."""
    numbers: list[int] = []
    total, current = 0, 0
    rank: int | None = None  # разряд последнего слова числа; None — число только начато
    for value in run:
        if value == _THOUSAND:
            total, current, rank = total + (current or 1) * _THOUSAND, 0, None
            continue
        if rank is not None and _rank(value) >= rank:
            numbers.append(total + current)
            total, current = 0, 0
        current += value
        rank = 1 if value in _TEENS else _rank(value)
    if run:
        numbers.append(total + current)
    return numbers


def _rank(value: int) -> int:
    """Разряд слова: сотни, десятки (и «-надцать»), единицы."""
    if value >= 100:
        return 3
    return 2 if value >= 10 else 1
