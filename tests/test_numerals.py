"""Числа словами в тексте модели: проверка «только числа из записи ученика» видит и их."""

import pytest

from hwcheck.pipeline.numerals import word_numbers


@pytest.mark.parametrize(
    ("text", "numbers"),
    [
        ("получилось девятьсот семьдесят два", [972]),
        ("вышло Пятьсот", [500]),
        ("сложил два и три", [2, 3]),
        ("числа два три", [2, 3]),  # разряды не убывают — это два числа, а не 5
        ("получил две тысячи", [2000]),
        ("тысяча двести пятнадцать", [1215]),
        ("двадцать пять тысяч сто", [25100]),
        ("из четырёх действий", [4]),
        ("к трём прибавил семнадцать", [3, 17]),
        ("двадцать, тридцать", [20, 30]),  # запятая между словами — разные числа
        ("сто и ещё сорок", [100, 40]),
    ],
)
def test_cardinals_are_read(text: str, numbers: list[int]) -> None:
    assert word_numbers(text) == numbers


@pytest.mark.parametrize(
    "text",
    [
        "перенёс десяток и сложил сотни с единицами",
        "первым действием нашёл сумму, вторым — разность",
        "сначала сложил, потом вычел",
        "одновременно и правильно, семья пятёрок",
        "",
    ],
)
def test_place_values_ordinals_and_lookalikes_are_not_numbers(text: str) -> None:
    assert word_numbers(text) == []
